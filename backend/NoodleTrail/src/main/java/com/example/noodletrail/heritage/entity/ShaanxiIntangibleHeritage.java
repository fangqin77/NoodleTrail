package com.example.noodletrail.heritage.entity;


public class ShaanxiIntangibleHeritage {
    private Integer id;
    private String heritageName;
    private String heritageType;
    private String imageUrl;
    private String videoUrl;
    private String historicalOrigin;
    private String contentIntroduction;

    public ShaanxiIntangibleHeritage() {
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public String getHeritageName() {
        return heritageName;
    }

    public void setHeritageName(String heritageName) {
        this.heritageName = heritageName;
    }

    public String getHeritageType() {
        return heritageType;
    }

    public void setHeritageType(String heritageType) {
        this.heritageType = heritageType;
    }

    public String getImageUrl() {
        return imageUrl;
    }

    public void setImageUrl(String imageUrl) {
        this.imageUrl = imageUrl;
    }

    public String getVideoUrl() {
        return videoUrl;
    }

    public void setVideoUrl(String videoUrl) {
        this.videoUrl = videoUrl;
    }

    public String getHistoricalOrigin() {
        return historicalOrigin;
    }

    public void setHistoricalOrigin(String historicalOrigin) {
        this.historicalOrigin = historicalOrigin;
    }

    public String getContentIntroduction() {
        return contentIntroduction;
    }

    public void setContentIntroduction(String contentIntroduction) {
        this.contentIntroduction = contentIntroduction;
    }
}
